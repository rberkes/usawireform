export function StateIcon({
  abbr,
  className,
  title,
}: {
  abbr: string;
  className?: string;
  title?: string;
}) {
  const code = abbr.toUpperCase();
  const state = getStateByAbbr(code);
  const label = title ?? state?.name ?? code;
  const outline = OUTLINES[code];

  if (!outline) {
    return (
      <span
        className={cx(
          "inline-flex items-center justify-center border border-current font-mono text-[0.32em] font-medium tracking-[0.18em] uppercase",
          className,
        )}
        aria-label={label}
        title={label}
      >
        {code}
      </span>
    );
  }

  const [, , width, height] = outline.viewBox.split(" ").map(Number);

  return (
    <svg
      viewBox={outline.viewBox}
      preserveAspectRatio="xMidYMid meet"
      className={cx("shrink-0", className)}
      style={{ aspectRatio: `${width} / ${height}` }}
      fill="currentColor"
      fillRule="evenodd"
      role="img"
      aria-label={label}
    >
      <title>{label}</title>
      <path d={outline.d} />
    </svg>
  );
}

export function StateMark({
  abbr,
  href,
  tone = "onDark",
  size = "hero",
}: {
  abbr: string;
  href?: string;
  tone?: "onDark" | "onLight";
  size?: "hero" | "card";
}) {
  const state = getStateByAbbr(abbr);
  const name = state?.name ?? abbr;
  const hero = size === "hero";
  const className = cx(
    "flex flex-col items-center gap-2 text-center no-underline",
    tone === "onDark"
      ? "text-white/80 hover:text-white"
      : "text-muted hover:text-foreground",
  );
  const inner = (
    <>
      <StateIcon
        abbr={abbr}
        title={name}
        className={hero ? "h-20 w-auto sm:h-28" : "h-12 w-auto"}
      />
      <span
        className={cx(
          "font-mono tracking-[0.2em] uppercase",
          hero ? "text-[11px]" : "text-[10px]",
        )}
      >
        {abbr}
        <span className="mt-0.5 block tracking-[0.16em]">{name}</span>
      </span>
    </>
  );

  if (href) {
    return (
      <Link href={href} className={className} aria-label={`Quotes from ${name}`}>
        {inner}
      </Link>
    );
  }

  return (
    <div className={className} aria-label={`Quotes from ${name}`}>
      {inner}
    </div>
  );
}
